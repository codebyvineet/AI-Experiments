"""LangGraph state definitions for multi-agent orchestration.

This module defines the state schema for the LangGraph agent system.
State is automatically checkpointed to MongoDB for persistence.
"""

from typing import TypedDict, Annotated, List, Dict, Any, Optional, Literal
from operator import add
from datetime import datetime


class PlanStep(TypedDict, total=False):
    """A single step in the execution plan."""
    step_id: str
    phase: Literal["research", "analysis", "execution", "data_operations", "validation"]
    description: str
    agent_type: Literal["research", "execution", "validation"]
    execution_mode: Literal["parallel", "sequential"]
    sub_tasks: List[Dict[str, Any]]
    reasoning: str
    mcp_tools_used: List[str]
    status: Literal["pending", "running", "completed", "failed", "authorization_failed"]
    result: Optional[Dict[str, Any]]


class TaskResult(TypedDict, total=False):
    """Result from executing a task."""
    task_name: str
    tool: Optional[str]
    status: Literal["success", "failed", "authorization_failed"]
    result: Any
    error: Optional[str]
    duration_ms: int


class AgentState(TypedDict, total=False):
    """
    State for the LangGraph multi-agent system.
    
    This state is automatically persisted to MongoDB via AsyncMongoDBSaver.
    The 'messages' and 'results' fields use reducers to accumulate values
    across parallel execution branches.
    
    Attributes:
        session_id: Unique session identifier
        user_id: User who initiated the session
        token: JWT token for MCP tool authorization
        goal: The user's goal/request
        plan: List of plan steps generated by planner
        current_step: Index of current step being executed
        results: Accumulated results from all tasks (reducer: add)
        messages: Chat history (reducer: add)
        status: Overall session status
        approved: Whether plan has been approved for execution
        error: Error message if execution failed
        summary: Final execution summary
    """
    # Session metadata
    session_id: str
    user_id: str
    token: str  # JWT for MCP authorization
    
    # Goal and planning
    goal: str
    plan: List[PlanStep]
    current_step: int
    
    # Execution state - use reducers for parallel accumulation
    results: Annotated[List[TaskResult], add]
    messages: Annotated[List[Dict[str, Any]], add]
    
    # Status tracking
    status: Literal["initialized", "planning", "awaiting_approval", "executing", "completed", "failed"]
    approved: bool
    error: Optional[str]
    
    # Final output
    summary: Optional[Dict[str, Any]]


def create_initial_state(
    session_id: str,
    user_id: str,
    goal: str,
    token: str
) -> AgentState:
    """Create initial state for a new agent session."""
    return AgentState(
        session_id=session_id,
        user_id=user_id,
        token=token,
        goal=goal,
        plan=[],
        current_step=0,
        results=[],
        messages=[{
            "role": "user",
            "content": goal,
            "timestamp": datetime.utcnow().isoformat()
        }],
        status="initialized",
        approved=False,
        error=None,
        summary=None
    )
